// Bakes procedural albedo, normal and roughness maps as JPEG data into textures-baked.js.
const {chromium}=require('/Users/kriti/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');const fs=require('fs'),path=require('path'),vm=require('vm');
(async()=>{
 const root=path.resolve(process.argv[2]);
 const only=process.argv.find(a=>a.startsWith('--only='))?.slice('--only='.length);
 const br=await chromium.launch({executablePath:process.env.BROWSER_BIN||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
 const p=await br.newPage();await p.setContent('<html><body></body></html>');
 await p.addScriptTag({content:fs.readFileSync(path.join(root,'model/three.min.js'),'utf8')});
 await p.addScriptTag({content:fs.readFileSync(path.join(root,'model/realism.js'),'utf8')});
 const t0=Date.now();
 const out=await p.evaluate(({qa,qr,qn})=>{
  const sets=window.JAIPUR_REALISM.buildProcedural({capabilities:{getMaxAnisotropy:()=>8}},'high');
  const res={};
  for(const [name,s] of Object.entries(sets)){
   res[name]={sizeFt:s.sizeFt,grain:!!s.grain,map:s.map.image.toDataURL('image/jpeg',qa),normalMap:s.normalMap.image.toDataURL('image/jpeg',qn),roughnessMap:s.roughnessMap.image.toDataURL('image/jpeg',qr),px:s.map.image.width};
  }
  return res;
 },{qa:.9,qr:.85,qn:.92});
 if(only){
  if(!out[only])throw new Error('Unknown texture family: '+only);
  const sandbox={window:{}};
  vm.runInNewContext(fs.readFileSync(path.join(root,'model/textures-baked.js'),'utf8'),sandbox);
  const updated={...sandbox.window.JAIPUR_TEXDATA,[only]:out[only]};
  for(const key of Object.keys(out))if(key!==only)delete out[key];
  fs.writeFileSync(path.join(root,'model/textures-baked.js'),'/* R-008 baked textures: generated by realism.js (procedural), stored as images so the walkthrough loads instantly. */\nwindow.JAIPUR_TEXDATA='+JSON.stringify(updated)+';\n');
 }else fs.writeFileSync(path.join(root,'model/textures-baked.js'),'/* R-008 baked textures: generated by realism.js (procedural), stored as images so the walkthrough loads instantly. */\nwindow.JAIPUR_TEXDATA='+JSON.stringify(out)+';\n');
 let total=0;const lines=[];
 for(const [n,s] of Object.entries(out)){const kb=(s.map.length+s.normalMap.length+s.roughnessMap.length)/1024;total+=kb;lines.push(`${n.padEnd(10)} ${s.px}px  albedo ${(s.map.length/1024).toFixed(0)}KB  normal ${(s.normalMap.length/1024).toFixed(0)}KB  rough ${(s.roughnessMap.length/1024).toFixed(0)}KB`);}
 console.log(lines.join('\n'),'\nTOTAL base64 KB',total.toFixed(0),'bake time',((Date.now()-t0)/1000).toFixed(1)+'s');
 await br.close();
})();
